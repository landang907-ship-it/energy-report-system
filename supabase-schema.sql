-- 1. WATER READINGS - Bảng nước
-- ============================================
create table if not exists water_readings (
    id bigint generated by default as identity primary key,
    date date not null,
    shift text not null check (shift in ('sang', 'toi')),
    location_code text not null,
    location_name_vi text,
    location_name_cn text,
    value decimal(10, 3),
    unit text default 'm3',
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);

-- Index cho tìm kiếm nhanh
create index if not exists water_readings_date_idx on water_readings(date);
create index if not exists water_readings_date_shift_idx on water_readings(date, shift);
create index if not exists water_readings_location_idx on water_readings(location_code);

-- RLS Policy
alter table water_readings enable row level security;
create policy "Enable read for authenticated users" on water_readings for select to authenticated using (true);
create policy "Enable insert for authenticated users" on water_readings for insert to authenticated with check (true);
create policy "Enable update for authenticated users" on water_readings for update to authenticated using (true);

