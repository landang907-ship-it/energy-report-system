-- Hàm lấy tổng năng lượng theo tháng
create or replace function get_monthly_totals(p_start_date date, p_end_date date)
returns table (
    energy_type text,
    total_value numeric
) as $$
begin
    return query
    select 'water'::text, coalesce(sum(value), 0) from water_readings where date between p_start_date and p_end_date
    union all
    select 'electric'::text, coalesce(sum(value), 0) from electric_readings where date between p_start_date and p_end_date
    union all
    select 'gas'::text, coalesce(sum(value), 0) from gas_readings where date between p_start_date and p_end_date
    union all
    select 'steam'::text, coalesce(sum(value), 0) from steam_readings where date between p_start_date and p_end_date;
end;
$$ language plpgsql security definer;

