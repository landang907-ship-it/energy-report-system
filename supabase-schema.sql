-- 6. USERS/PROFILES - Bảng người dùng (mở rộng)
-- ============================================
create table if not exists user_profiles (
    id uuid references auth.users on delete cascade primary key,
    email text,
    full_name text,
    role text default 'user' check (role in ('admin', 'user', 'viewer')),
    department text,
    phone text,
    is_active boolean default true,
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now()
);

-- RLS Policy
alter table user_profiles enable row level security;
create policy "Users can view own profile" on user_profiles for select to authenticated using (auth.uid() = id);
create policy "Users can update own profile" on user_profiles for update to authenticated using (auth.uid() = id);
create policy "Admins can manage all profiles" on user_profiles for all to authenticated using (
    exists (
        select 1 from user_profiles
        where id = auth.uid() and role = 'admin'
    )
);

-- Auto create profile on signup
create or replace function public.handle_new_user()
returns trigger as $$
begin
    insert into public.user_profiles (id, email, full_name)
    values (new.id, new.email, new.raw_user_meta_data->>'full_name');
    return new;
end;
$$ language plpgsql security definer;

create or replace trigger on_auth_user_created
    after insert on auth.users
    for each row execute procedure public.handle_new_user();

