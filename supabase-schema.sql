-- 8. VIEWS - Tạo view cho dashboard
-- ============================================

-- View tổng hợp nước theo ngày
create or replace view water_daily_summary as
select 
    date,
    shift,
    count(*) as location_count,
    sum(value) as total_value,
    avg(value) as avg_value,
    max(value) as max_value,
    min(value) as min_value
from water_readings
group by date, shift
order by date desc, shift;

-- View tổng hợp điện theo ngày
create or replace view electric_daily_summary as
select 
    date,
    shift,
    count(*) as location_count,
    sum(value) as total_value,
    avg(value) as avg_value,
    max(value) as max_value,
    min(value) as min_value
from electric_readings
group by date, shift
order by date desc, shift;

-- View tổng hợp gas theo ngày
create or replace view gas_daily_summary as
select 
    date,
    shift,
    count(*) as product_count,
    sum(value) as total_value,
    avg(value) as avg_value
from gas_readings
group by date, shift
order by date desc, shift;

-- View tổng hợp hơi nóng theo ngày
create or replace view steam_daily_summary as
select 
    date,
    shift,
    count(*) as process_count,
    sum(value) as total_value,
    avg(value) as avg_value
from steam_readings
group by date, shift
order by date desc, shift;

